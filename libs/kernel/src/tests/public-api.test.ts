function frozenThrough(value: unknown): boolean {
  if (typeof value !== 'object' || value === null) return true;

  return Object.isFrozen(value) && Object.values(value).every((member: unknown) => frozenThrough(member));
}

function exportedNames(): string[] {
  const entry = fileURLToPath(new URL('../index.ts', import.meta.url));
  const program = ts.createProgram([entry], {
    allowImportingTsExtensions: true,
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    noEmit: true,
    strict: true,
    target: ts.ScriptTarget.ES2023,
    types: [],
  });
  const source = program.getSourceFile(entry);
  const checker = program.getTypeChecker();
  const module = source === undefined ? undefined : checker.getSymbolAtLocation(source);

  if (module === undefined) throw new Error('The entry point of the kernel has no exports.');

  return checker.getExportsOfModule(module).map((symbol) => symbol.getName()).sort();
}
