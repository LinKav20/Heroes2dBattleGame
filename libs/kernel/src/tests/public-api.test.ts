import * as kernel from '../index.ts';

describe('the public API of the kernel', () => {
  it('exports only these values', () => {
    expect(Object.keys(kernel).sort()).toStrictEqual(VALUES);
  });

  it('exports only these types', () => {
    const types = exportedNames().filter((name) => !VALUES.includes(name));

    expect(types).toStrictEqual(TYPES);
  });

  it('freezes its constants', () => {
    const constants = [
      kernel.COMPARISON_OPERATORS,
      kernel.EFFECT_NOT_APPLIED_REASONS,
      kernel.KERNEL_ONLY_STEPS,
      kernel.REFERENCE_FORMATS,
      kernel.SCHEMA_REFERENCES,
      kernel.CONDITION_SCHEMA,
      kernel.FORMULA_SCHEMA,
      kernel.KERNEL_CONDITIONS,
      kernel.KERNEL_EVENTS,
      kernel.KERNEL_EXTENSION_KINDS,
      kernel.KERNEL_FORMULAS,
      kernel.KERNEL_OPERATIONS,
      kernel.KERNEL_STEPS,
      kernel.MIGRATION_FAILURES,
      kernel.NAME_SCHEMA,
      kernel.OPERATION_SCHEMA,
      kernel.RANDOM_SOURCES,
      kernel.REJECTION_CODES,
      kernel.REJECTION_REASONS,
      kernel.RNG_FAILURES,
      kernel.ROLE_SCHEMA,
      kernel.ROLL_VISIBILITIES,
      kernel.SUBJECT_KINDS,
      kernel.SUBJECT_ROLES,
      kernel.VISIBLE_TO_NONE,
    ];

    expect(constants.every((constant) => frozenThrough(constant))).toBe(true);
  });

  it('names every built-in extension and every reason of the kernel with the prefix of the kernel', () => {
    const names = [
      ...Object.values(kernel.KERNEL_CONDITIONS),
      ...Object.values(kernel.KERNEL_EVENTS),
      ...Object.values(kernel.KERNEL_FORMULAS),
      ...Object.values(kernel.KERNEL_OPERATIONS),
      ...Object.values(kernel.KERNEL_STEPS),
      ...Object.values(kernel.REJECTION_REASONS),
    ];

    expect(names.every((name) => name.startsWith(`${kernel.KERNEL_PREFIX}:`))).toBe(true);
    expect(new Set(names).size).toBe(names.length);
  });
});

